/**
 * Flattened Master Catalog of all 22 Major Moons
 */
export const ALL_MOONS: MoonDefinition[] = CELESTIAL_BODIES.flatMap(
  (b) => b.visual.moons || []
);

export function getCelestialBody(id: string): CelestialBodyDefinition | undefined {
  return CELESTIAL_BODIES.find((b) => b.id === id);
}

export function getMoon(id: string): MoonDefinition | undefined {
  return ALL_MOONS.find((m) => m.id === id);
}

export function getDwarfPlanet(id: string): DwarfPlanetDefinition | undefined {
  return DWARF_PLANETS.find((d) => d.id === id);
}

export function getSpacecraft(id: string): SpacecraftDefinition | undefined {
  return SPACECRAFT.find((s) => s.id === id);
}
